cat("\n== theta SD ==\n")
cat("sd(theta) runs:", sd(mrot_df$metric_value), " by site:\n"); print(mrot_df |> summarise(sd=sd(metric_value), m=mean(metric_value), .by=site_label))
th <- mrot_df |> left_join(sex_data_cleaned, by="user_id") |> mutate(site_label=factor(site_label))
m_age <- lmer(metric_value ~ age + site_label + (1|user_id), th); print(round(fixef(m_age)["age"],3))
cat("age slope in SD per yr:", fixef(m_age)["age"]/sd(th$metric_value), "\n")
cat("\n== age nonlinearity in theta ==\n")
m1 <- lmer(metric_value ~ age * site_label + (1|user_id), th, REML=FALSE)
m2 <- lmer(metric_value ~ (age + I(age^2)) * site_label + (1|user_id), th, REML=FALSE)
print(anova(m1,m2))
m3 <- lmer(metric_value ~ age + I(age^2) + site_label + (1|user_id), th, REML=FALSE)
m4 <- lmer(metric_value ~ age + site_label + (1|user_id), th, REML=FALSE); print(anova(m4,m3))
cat("\n== sex on theta: CI, site interaction ==\n")
ths <- th |> filter(!is.na(sex)) |> mutate(sex=factor(sex)); contrasts(ths$sex) <- contr.sum(levels(ths$sex))
a0 <- lmer(metric_value ~ age*sex*site_label + (1|user_id), ths, REML=FALSE)
a1 <- lmer(metric_value ~ age*site_label + sex + (1|user_id), ths, REML=FALSE)
a2 <- lmer(metric_value ~ age*site_label + sex*site_label + (1|user_id), ths, REML=FALSE)
a3 <- lmer(metric_value ~ age*sex + site_label + (1|user_id), ths, REML=FALSE)
print(anova(a1,a2)); 
# sex main effect (Male-Female) in additive model w CI
ae <- lmer(metric_value ~ age + site_label + sex + (1|user_id), ths)
sx <- summary(ae)$coefficients["sex1",]; print(sx)
cat("Female-Male diff (2*coef):", 2*sx[1], " 95% CI +-", 1.96*2*sx[2], " in SD:", 2*sx[1]/sd(ths$metric_value), " +-", 1.96*2*sx[2]/sd(ths$metric_value), "\n")
cat("sex counts by site:\n"); print(ths |> distinct(user_id,site_label,sex) |> count(site_label,sex))
